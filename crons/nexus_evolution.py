# Placeholder strings that indicate a failed/empty LLM generation
_PLACEHOLDER_MARKERS = (
    "Suggestion 1",
    "Suggestion 2",
    "placeholder",
    "TODO",
    "[FILL",
)

def _is_valid_content(text: str) -> bool:
    """Return True only if text is non-empty and free of known placeholder markers."""
    stripped = text.strip()
    if not stripped:
        return False
    for marker in _PLACEHOLDER_MARKERS:
        if marker in stripped:
            logger.warning(f"NEXUS-V2: Quality gate rejected content containing marker: {marker!r}")
            return False
    return True


